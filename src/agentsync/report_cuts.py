"""The values both setup reports cut by, in one place (B13 round 39 ruling 133; privacy).

Ruling 126's halves were ported by hand, the Python report's in :mod:`agentsync.setup_report` and the shell
fallback report's in ``scripts/install.sh``, and they drifted: the shell stopped holding agentsync's verbs
once a folder began with one (C1625), kept an unregistered tenant (C1626), kept 26 format characters
``safe_text`` drops (C1628), and the Python report printed the blank, hyphen and underscore spellings of a
name holding a control byte (C1629). So every value the two cut by lives here, once, as data:
:mod:`agentsync.setup_report` builds its separators, its provider rule and its aliases from it, and
``scripts/install.sh`` carries the block :func:`shell_block` generates between ``# BEGIN report_cuts`` and
``# END report_cuts``, which a test holds byte for byte to this module. The shell never reads this module
from the installed agentsync, which may be older (C1655): the block is generated in the checkout.

Data and the standard library only, so the block can be generated by any build of the checkout.
"""

