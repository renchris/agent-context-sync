@functools.cache
def agentsync_verbs() -> tuple[str, ...]:
    """agentsync's own commands, read from the ones ``cli.build_parser`` registers, hidden ones included,
    longest first: both reports hold one whole after ``agentsync `` (B13 round 38 C1425, ruling 126). Empty
    when cli does not import (the report must build even then): nothing is held."""
    try:
        import argparse  # noqa: PLC0415

        from agentsync import cli  # noqa: PLC0415 - lazy: cli imports the report, never the reverse

        parser = cli.build_parser()
    except Exception:  # any failure keeps the report working, with no verb held
        return ()
    names = {
        name
        for action in parser._actions
        if isinstance(action, argparse._SubParsersAction)
        for name in action.choices
    }
    return tuple(sorted(names, key=lambda v: (-len(v), v)))


def _runs(points: list[int]) -> list[tuple[int, int]]:
    out: list[tuple[int, int]] = []
    for c in sorted(set(points)):
        if out and out[-1][1] == c - 1:
            out[-1] = (out[-1][0], c)
        else:
            out.append((c, c))
    return out


_SEP_LITERAL = {0x20: " ", 0x09: "\\t", 0x5F: "_", 0x5C: "\\\\"}  # the hyphen goes last, as itself


def sep_class() -> str:
    """:data:`SEPARATORS` as one regular-expression bracket class (Python's ``re``)."""
    lits = [_SEP_LITERAL[c] for c in (0x20, 0x09, 0x5F, 0x5C)]
    rest = [c for c in SEPARATORS if c not in _SEP_LITERAL and c != 0x2D]
    ranges = "".join(f"\\x{a:02x}" if a == b else f"\\x{a:02x}-\\x{b:02x}" for a, b in _runs(rest))
    return "[" + "".join(lits) + ranges + "-]"


def _shell_sep_class() -> str:
    """:data:`SEPARATORS` as an awk bracket class with octal bytes, NUL left out (no shell string holds
    one)."""
    lits = [_SEP_LITERAL[c] for c in (0x20, 0x09, 0x5F, 0x5C)]
    rest = [c for c in SEPARATORS if c not in _SEP_LITERAL and c not in (0x2D, 0x00)]
    ranges = "".join(f"\\{a:03o}" if a == b else f"\\{a:03o}-\\{b:03o}" for a, b in _runs(rest))
    return "[" + "".join(lits) + ranges + "-]"


def format_chars() -> frozenset[int]:
    """Every code point :data:`FORMAT_RANGES` holds."""
    return frozenset(c for lo, hi in FORMAT_RANGES for c in range(lo, hi + 1))


def _any_case(word: str) -> str:
    return "".join(f"[{c.upper()}{c.lower()}]" if c.isalpha() else c for c in word)


def provider_kept_pattern() -> str:
    """The provider folders after ``CloudStorage`` the path cut keeps, as one pattern that Python's ``re``
    (with ``fullmatch``) and a POSIX ERE (between ``^`` and ``$``) read alike: an app's name
    (:data:`PROVIDER_APPS`), ``-SharedLibraries`` for a shared library, then nothing, a hyphen and
    placeholders only (``OneDrive-<org-1>``), or a hyphen and a domain ``setup_report._org_of`` reads as
    naming no organisation: a :data:`GENERIC_DOMAINS` word or the app's own name, in any case
    (``OneDrive-Personal``, ``Box-Box``). Never a literal tenant (``OneDrive-Fabrikam``, ``Fabrikam-<org-1>``,
    ``OneDrive-Personal-Fabrikam``; B13 round 39 C1634 with C1626). Spelled out per app, since awk has no
    backreference; every letter in any case as a bracket pair, since an ERE has no case flag."""
    domains = "|".join(_any_case(d) for d in sorted(GENERIC_DOMAINS))
    held = "(<[a-z]+(-[0-9]+)?>)+"
    alts = [f"{app}(-{SHARED_LIBRARIES})?(-{held}|-({domains}|{_any_case(app)}))?" for app in PROVIDER_APPS]
    return "(" + "|".join(alts) + ")"


def _octal(ch: str) -> str:
    return "".join(f"\\{b:03o}" for b in ch.encode("utf-8"))


def shell_block() -> str:
    """The block ``scripts/install.sh`` carries between ``# BEGIN report_cuts`` and ``# END report_cuts``,
    those two lines included, each value a shell assignment in single quotes that an awk reads through
    ENVIRON (BSD awk takes no newline in ``-v``): ``AGENTSYNC_VERBS`` (longest first), ``CUT_DRIVE``
    (:data:`GENERIC_FOLDERS`), ``CUT_AGENT`` (:data:`AGENT_WORDS`), ``CUT_APPS``, ``CUT_DOMAINS``,
    ``CUT_PROVIDER_KEPT`` (:func:`provider_kept_pattern`, anchored), ``CUT_SEP`` (:data:`SEPARATORS` as an awk
    bracket class), ``CUT_CF`` (each format character one UTF-8 alternative in octal), ``CUT_Q32_OCTAL``
    (:data:`BASH32_UTF8_OCTAL` as a bracket class); then, since B13 round 40 ruling 137, ``CUT_HEADS_<RULE>``
    for each :data:`PATH_RULES` rule (its :data:`PATH_HEADS`, ``|``-joined, in table order),
    ``CUT_REFUSED_HEADS`` (:data:`REFUSED_HEADS`, written in double quotes, since one holds an apostrophe),
    ``CUT_DEL_ESCAPED`` (:data:`DEL_ESCAPED`), ``CUT_FREE_HEAD`` (:data:`FREE_PROVIDER_HEAD`) and
    ``CUT_FREE_END`` (:data:`FREE_WORD_END` as an awk bracket class of octal bytes) and ``CUT_FREE_TRAIL``
    (:data:`FREE_WORD_TRAIL`)."""
    values = {
        "AGENTSYNC_VERBS": "|".join(agentsync_verbs()),
        "CUT_DRIVE": "|".join(sorted(GENERIC_FOLDERS)),
        "CUT_AGENT": "|".join(sorted(AGENT_WORDS)),
        "CUT_APPS": "|".join(PROVIDER_APPS),
        "CUT_DOMAINS": "|".join(sorted(GENERIC_DOMAINS)),
        "CUT_PROVIDER_KEPT": f"^{provider_kept_pattern()}$",
        "CUT_SEP": _shell_sep_class(),
        "CUT_CF": "|".join(_octal(chr(c)) for c in sorted(format_chars())),
        "CUT_Q32_OCTAL": "["
        + "".join(
            f"\\{a:03o}" if a == b else f"\\{a:03o}-\\{b:03o}" for a, b in _runs(list(BASH32_UTF8_OCTAL))
        )
        + "]",
        **{
            f"CUT_HEADS_{rule.upper()}": "|".join(head for head, r in PATH_HEADS if r == rule)
            for rule in PATH_RULES
        },
        "CUT_DEL_ESCAPED": "|".join(DEL_ESCAPED),
        "CUT_FREE_HEAD": FREE_PROVIDER_HEAD,
        "CUT_FREE_END": "[" + "".join(f"\\{c:03o}" for c in FREE_WORD_END) + "]",
        "CUT_FREE_TRAIL": FREE_WORD_TRAIL,
    }
    assert not any("'" in v or "\n" in v for v in values.values())
    assert all(h and "|" not in h for h, _r in PATH_HEADS) and all("|" not in h for h in REFUSED_HEADS)
    # double quotes: a head holds an apostrophe; none holds a character double quotes expand
    assert not any(c in h for h in REFUSED_HEADS for c in '"$`\\\n')
    refused = "|".join(REFUSED_HEADS)
    lines = [
        "# BEGIN report_cuts",
        "# Generated by agentsync.report_cuts.shell_block() (B13 round 39 ruling 133, round 40 ruling",
        "# 137): the values and argument forms both reports cut by, held byte for byte to the generator",
        "# by a test. Change src/agentsync/report_cuts.py, never this block.",
        *(
            line
            for name, value in values.items()
            # a literal ~, which the readers match and never expand
            for line in (["# shellcheck disable=SC2088"] if value.startswith("~") else [])
            + [f"{name}='{value}'"]
        ),
        f'CUT_REFUSED_HEADS="{refused}"',
        "# END report_cuts",
    ]
    return "\n".join(lines) + "\n"
